const LOCALES = Object.keys(TEXTOS);

function buscar(obj, caminho) {
  return caminho.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
}

function interpolar(texto, vars) {
  if (!vars) return texto;
  return texto.replace(/\{(\w+)\}/g, (m, chave) => (vars[chave] !== undefined ? String(vars[chave]) : m));
}

// t(locale, 'grupo.chave', { var: valor }) — interpolação simples de `{var}`.
// Locale desconhecido ou chave ausente no locale pedido cai pro pt.
export function t(locale, chave, vars) {
  const loc = LOCALES.includes(locale) ? locale : 'pt';
  let texto = buscar(TEXTOS[loc], chave);
  if (texto === undefined) texto = buscar(TEXTOS.pt, chave);
  if (texto === undefined) return chave;
  if (typeof texto !== 'string') return texto;
  return interpolar(texto, vars);
}

export function locales() {
  return LOCALES;
}
